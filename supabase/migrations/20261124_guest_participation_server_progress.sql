-- Anonymous per-browser progress. NOT verified eligibility for financial rewards.
create table if not exists public.visitor_sessions (
  id uuid primary key default gen_random_uuid(),
  token_hash text not null unique,
  created_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now()
);
create table if not exists public.visitor_stamps (
  id bigint generated by default as identity primary key,
  session_id uuid not null references public.visitor_sessions(id) on delete cascade,
  tour_id text not null references public.tours(id) on delete cascade,
  attraction_id bigint not null references public.attractions(id) on delete cascade,
  evidence text not null default 'client_reported' check (evidence = 'client_reported'),
  earned_at timestamptz not null default now(),
  unique(session_id, attraction_id)
);
create index if not exists visitor_stamps_session_tour_idx on public.visitor_stamps(session_id, tour_id);
alter table public.visitor_sessions enable row level security;
alter table public.visitor_stamps enable row level security;
revoke all on public.visitor_sessions from anon, authenticated;
revoke all on public.visitor_stamps from anon, authenticated;
revoke all on sequence public.visitor_stamps_id_seq from anon, authenticated;
comment on table public.visitor_stamps is 'Informational guest stamps based on client-reported recognition; NOT valid evidence for monetary coupon issuance.';